func init() {
	for _, list := range [][]Rule{rules, migration, source, loaded, applied} {
		for i := range list {
			list[i].Fix = fixes[list[i].ID]
		}
	}
	for id, r := range ruleByID {
		r.Fix = fixes[id]
		ruleByID[id] = r
	}
}

// Fix tells how a finding of the check is put right ("" for a check the
// tool does not know).
func Fix(id string) string { return fixes[id] }
